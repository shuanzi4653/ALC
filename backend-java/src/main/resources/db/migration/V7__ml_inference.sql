-- ============================================================
-- V7 轨1 模型推理留痕：把「模型这一轮说了什么」记在库里
-- ============================================================
--
-- 为什么需要这张表：
--   0.10.1（Beta） 之前 `/track1/ml` 是个 stub（恒返回 not_implemented），
--   所以"模型表现如何"这个问题从来没有过一次可查的答案。接上真模型之后，
--   如果没有留痕，"模型和规则吵过几次架、吵在哪一档"就只存在于日志里，
--   而日志会轮转 —— 成效页那张三列表格就成了手写数字。
--
-- 存的粒度 = 一次推理请求一行。**不聚合**：
--   聚合（按小时/按档位计数）一旦落成表，就再也没法回头改口径；
--   明细留着，成效页想按什么分组都还能算。
--
-- 存什么、不存什么（这一行是本表的边界，改动前先读完）：
--   存   — 档位、置信度、top3 归因、模型/判据版本、同轮规则档位、输入指纹。
--   不存 — **原始气象快照**。理由是复算争议不需要原文：快照由
--          `(城市, 时间, 数据源)` 唯一确定，指纹足够定位；而原文是外部数据，
--          存进来只会让"我们的库里为什么有一份别人家的气象数据"成为新问题。
--          同理，**不放任何凭据**（与 V6 的配额表一致）。
--
-- ⚠️ 列名避开保留字：本表刻意不用 `day` / `value` / `level` 之外的裸关键字——
--   `level` 在 H2 里不是保留字（V1 的 alert 表已在用），`agree` 也不是，
--   但 `day` 是（见 V6 顶部那段：INTERVAL 字面量的单位）。写新列前先照这个规矩核一遍。
--
-- 只增不改：本表的行是一次推理的**历史记录**，语义上不可变。
--   要纠正一条错误记录，正确做法是再写一行并让它成为最新，而不是 UPDATE 旧行。
--
-- 幂等：IF NOT EXISTS；Flyway 另行记录版本，重复执行无副作用。
-- ============================================================

CREATE TABLE IF NOT EXISTS ml_inference (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 同一次运行台的轮次标识（`/traffic/session` 的 sessionId）。为空表示独立调用，
    -- 不代表"缺失"——研判页的手动试算不需要会话。
    session_id      VARCHAR(80),
    -- 样本键：`<城市>-<YYYY-MM-DDTHHMM>`，与训练样本同一套命名，便于把线上样本
    -- 直接拎出来和训练集对照（"这条线上一直在判错"是不是同类样本，靠它对）。
    sample_key      VARCHAR(64),
    -- 匿名工作区（0.10.x 已无登录）。空值 = **未标识**，不等于"默认工作区"。
    workspace_id    VARCHAR(64),
    -- 这一轮模型到底参与了没有。**单独一列，不用 level 凑**：
    -- 把"模型没参与"写成 level='UNAVAILABLE' 会让档位分布里多出一个不存在的档，
    -- 于是成效页那张"四档分布"要么多一根柱子，要么得靠一句隐性约定把它过滤掉 ——
    -- 而隐性约定会在下一个人改统计时失效。available 明确，统计就写 where available = true。
    available       BOOLEAN NOT NULL DEFAULT TRUE,
    -- 不可用的原因（MODEL_NOT_FOUND / MODEL_INVALID 等）。available=true 时必须为空。
    reason          VARCHAR(48),
    level           VARCHAR(16) NOT NULL,
    confidence      DECIMAL(5, 4),
    -- top1 与 top2 的概率差。单列出来是因为"置信度 0.45 且次高 0.44"和
    -- "置信度 0.45 且次高 0.05"在界面上必须长得不一样，而只存 confidence 分不出这两种。
    margin          DECIMAL(5, 4),
    low_confidence  BOOLEAN NOT NULL DEFAULT FALSE,
    -- 关键要素缺测 ≥3 个时为真：档位建立在训练中位数填充之上，不是看过天气给的。
    degraded        BOOLEAN NOT NULL DEFAULT FALSE,
    missing_count   INTEGER NOT NULL DEFAULT 0,
    -- top3 近似归因（JSON 数组）。**不是 SHAP**，字段名因此不叫 shap。
    top3            CLOB,
    -- 同轮规则档位与是否一致。rule_level 为空 = 该轮没有规则结果（不可比），
    -- 此时 agree 也必须为空 —— 把"不可比"写成 false 会被统计成"吵了一架"。
    rule_level      VARCHAR(16),
    agree           BOOLEAN,
    model_version   VARCHAR(32) NOT NULL,
    labels_version  VARCHAR(32),
    -- 输入快照指纹（对规范化后的要素串取 SHA-256）。用于定位争议，不用于复算原文。
    -- 用 VARCHAR 而不是 CHAR：Hibernate 把 Java String 映射成 varchar，写成 CHAR(64)
    -- 时 `ddl-auto=validate` 会报 "found [character (CHAR)] but expecting [varchar(64)]"。
    -- 而生产的 ddl-auto=none **不会**报 —— 它会在第一次 SELECT 这一列时才暴露。
    inputs_sha256   VARCHAR(64),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 成效页三列（档位分布 / 与规则一致性 / 模型可用率）都按时间倒序扫最近一段。
CREATE INDEX IF NOT EXISTS idx_ml_inference_created ON ml_inference (created_at);
-- 档位分布只统计 available=true 的行，这个复合索引让"最近一段 + 可用 + 按档位"一次走完。
CREATE INDEX IF NOT EXISTS idx_ml_inference_avail_level ON ml_inference (available, level);
-- 「最近 N 轮里模型和规则分歧了多少」要按会话捞。
CREATE INDEX IF NOT EXISTS idx_ml_inference_session ON ml_inference (session_id);
-- 按档位统计与按样本键回查。
CREATE INDEX IF NOT EXISTS idx_ml_inference_level ON ml_inference (level);
CREATE INDEX IF NOT EXISTS idx_ml_inference_sample ON ml_inference (sample_key);
