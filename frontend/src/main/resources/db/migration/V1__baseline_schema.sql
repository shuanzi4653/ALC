-- ============================================================
-- V1 基线：天窗智巡全部表结构
-- 说明：统一使用 IF NOT EXISTS，使「全新库」与「已有旧库」都幂等可执行。
--       NOT NULL 列一律带 DEFAULT，保证旧库补列时不因历史行空值而失败。
-- ============================================================

-- ---------- 智能体问答记录 ----------
CREATE TABLE IF NOT EXISTS agent_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer CLOB,
    latency_ms INTEGER NOT NULL DEFAULT 0,
    question CLOB,
    source VARCHAR(255),
    ts TIMESTAMP
);

-- ---------- 预警事件 ----------
CREATE TABLE IF NOT EXISTS alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advice CLOB,
    episode_id VARCHAR(255),
    factors CLOB,
    level VARCHAR(255),
    region VARCHAR(255),
    run_id VARCHAR(255),
    status VARCHAR(255),
    text CLOB,
    transition_version INTEGER NOT NULL DEFAULT 0,
    trigger_type VARCHAR(255),
    ts TIMESTAMP
);

-- ---------- 预警状态机（按 state_key 分区） ----------
CREATE TABLE IF NOT EXISTS alert_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id VARCHAR(255),
    last_seen_at TIMESTAMP,
    level VARCHAR(255),
    recovery_count INTEGER NOT NULL DEFAULT 0,
    state VARCHAR(255),
    state_key VARCHAR(300) NOT NULL,
    transition_version INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP,
    CONSTRAINT uk_alert_state_key UNIQUE (state_key)
);

-- ---------- 监测运行（运行级一致性） ----------
CREATE TABLE IF NOT EXISTS monitoring_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configured_mode VARCHAR(255),
    degrade_reason VARCHAR(255),
    degraded BOOLEAN NOT NULL DEFAULT FALSE,
    effective_source VARCHAR(255),
    error_code VARCHAR(255),
    error_message VARCHAR(255),
    evaluated_at TIMESTAMP,
    forecast_json CLOB,
    ingested_at TIMESTAMP,
    obs_time VARCHAR(255),
    region_id VARCHAR(255),
    revision INTEGER NOT NULL DEFAULT 0,
    run_id VARCHAR(36) NOT NULL,
    scenario VARCHAR(255),
    snapshot_json CLOB,
    started_at TIMESTAMP,
    status VARCHAR(255),
    updated_at TIMESTAMP,
    CONSTRAINT uk_monitoring_run_id UNIQUE (run_id)
);

-- ---------- 预警投递 outbox ----------
CREATE TABLE IF NOT EXISTS outbox_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT,
    attempts INTEGER NOT NULL DEFAULT 0,
    channel VARCHAR(255),
    created_at TIMESTAMP,
    detail VARCHAR(255),
    due_at TIMESTAMP,
    event_key VARCHAR(255) NOT NULL,
    payload CLOB,
    status VARCHAR(255),
    updated_at TIMESTAMP,
    CONSTRAINT uk_outbox_event_key UNIQUE (event_key)
);

-- ---------- 推送日志 ----------
CREATE TABLE IF NOT EXISTS push_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT,
    channel VARCHAR(255),
    detail VARCHAR(255),
    latency_ms INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(255),
    target VARCHAR(255),
    ts TIMESTAMP
);

-- ---------- 每轮监测记录（SFI + 完整观测快照） ----------
CREATE TABLE IF NOT EXISTS sfi_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checks_json CLOB,
    cloud_cover DOUBLE NOT NULL DEFAULT 0,
    condition_text VARCHAR(255),
    configured_mode VARCHAR(255),
    degrade_reason VARCHAR(255),
    degraded BOOLEAN NOT NULL DEFAULT FALSE,
    effective_source VARCHAR(255),
    evaluated_at TIMESTAMP,
    hard_ban BOOLEAN NOT NULL DEFAULT FALSE,
    humidity DOUBLE NOT NULL DEFAULT 0,
    ingested_at TIMESTAMP,
    lat DOUBLE,
    level VARCHAR(255),
    lon DOUBLE,
    obs_time VARCHAR(255),
    precip_mmh DOUBLE NOT NULL DEFAULT 0,
    pressure_hpa DOUBLE NOT NULL DEFAULT 0,
    raw_sfi INTEGER NOT NULL DEFAULT 0,
    region_id VARCHAR(255),
    rule_version VARCHAR(255),
    run_id VARCHAR(255),
    scenario VARCHAR(255),
    sfi INTEGER NOT NULL DEFAULT 0,
    source VARCHAR(255),
    tempc DOUBLE NOT NULL DEFAULT 0,
    thunder_prob DOUBLE NOT NULL DEFAULT 0,
    ts TIMESTAMP,
    visibilitym DOUBLE NOT NULL DEFAULT 0,
    wind_deg INTEGER,
    wind_gust DOUBLE NOT NULL DEFAULT 0,
    wind_speed DOUBLE NOT NULL DEFAULT 0
);

-- ---------- 双轨推演结果 ----------
CREATE TABLE IF NOT EXISTS track_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement VARCHAR(255),
    fused_level VARCHAR(255),
    fused_sfi INTEGER NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 0,
    run_id VARCHAR(255),
    status VARCHAR(255),
    track1level VARCHAR(255),
    track1reason CLOB,
    track1sfi INTEGER NOT NULL DEFAULT 0,
    track2advice CLOB,
    track2confidence DOUBLE NOT NULL DEFAULT 0,
    track2factors CLOB,
    track2level VARCHAR(255),
    track2source VARCHAR(255),
    ts TIMESTAMP
);

-- ---------- 查询索引 ----------
CREATE INDEX IF NOT EXISTS idx_sfi_record_ts ON sfi_record (ts);
CREATE INDEX IF NOT EXISTS idx_sfi_record_region_source_rule ON sfi_record (region_id, effective_source, rule_version, ts);
CREATE INDEX IF NOT EXISTS idx_sfi_record_run_id ON sfi_record (run_id);
CREATE INDEX IF NOT EXISTS idx_alert_ts ON alert (ts);
CREATE INDEX IF NOT EXISTS idx_push_log_ts ON push_log (ts);
CREATE INDEX IF NOT EXISTS idx_monitoring_run_status ON monitoring_run (status);
CREATE INDEX IF NOT EXISTS idx_outbox_status_due ON outbox_event (status, due_at);
