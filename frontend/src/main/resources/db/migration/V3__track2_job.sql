-- 任务先入库再由有界 worker 领取，支持崩溃后收敛与幂等重放。
-- ============================================================

CREATE TABLE IF NOT EXISTS track2_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key VARCHAR(300) NOT NULL,
    run_id VARCHAR(255),
    region_id VARCHAR(255),
    job_kind VARCHAR(64) DEFAULT 'TRACK2',
    status VARCHAR(64),
    attempts INTEGER NOT NULL DEFAULT 0,
    due_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    error_code VARCHAR(255),
    CONSTRAINT uk_track2_job_key UNIQUE (job_key)
);

CREATE INDEX IF NOT EXISTS idx_track2_job_status ON track2_job (status);
CREATE INDEX IF NOT EXISTS idx_track2_job_run_id ON track2_job (run_id);
CREATE INDEX IF NOT EXISTS idx_track2_job_due ON track2_job (status, due_at);
